#!/usr/bin/env python3
"""Generate the Homebrew Cask from a versioned TiebaPure-Mac release archive."""
import argparse
import hashlib
import plistlib
import re
import zipfile
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("tag", help="Release tag, for example v0.1.0")
parser.add_argument("archive", type=Path, help="Downloaded TiebaPure-Mac-<version>.zip")
parser.add_argument(
    "--output",
    type=Path,
    default=Path(__file__).resolve().parents[2] / "Casks" / "tiebapure-mac.rb",
)
args = parser.parse_args()

match = re.fullmatch(r"v([0-9]+\.[0-9]+\.[0-9]+)", args.tag)
if not match:
    parser.error("Expected semantic release tag, for example v0.1.0")
version = match.group(1)

if args.archive.name != f"TiebaPure-Mac-{version}.zip":
    parser.error(f"Archive filename must be TiebaPure-Mac-{version}.zip")

digest = hashlib.sha256()
with args.archive.open("rb") as file:
    for block in iter(lambda: file.read(1024 * 1024), b""):
        digest.update(block)

with zipfile.ZipFile(args.archive) as archive:
    metadata = plistlib.loads(archive.read("TiebaPure-Mac.app/Contents/Info.plist"))
if metadata.get("CFBundleIdentifier") != "io.github.yamakze.TiebaPureMac" or metadata.get("CFBundleShortVersionString") != version:
    parser.error("Application identity or version in the archive does not match the release")

auto_updates = (
    "  auto_updates true\n\n"
    if metadata.get("SUPublicEDKey") and metadata.get("SUFeedURL")
    else ""
)

args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(f"""# Generated by scripts/lib/update-homebrew-cask.py from the release archive.
cask "tiebapure-mac" do
  version "{version}"
  sha256 "{digest.hexdigest()}"

  url "https://github.com/yamakze/TiebaPure-Mac/releases/download/v#{{version}}/TiebaPure-Mac-#{{version}}.zip"
  name "TiebaPure-Mac"
  desc "Native macOS client for Baidu Tieba"
  homepage "https://github.com/yamakze/TiebaPure-Mac"

  livecheck do
    url :url
    strategy :github_latest
  end

{auto_updates}  depends_on macos: ">= :sonoma"

  app "TiebaPure-Mac.app"
end
""")
print(f"Updated {args.output}: {version} · SHA-256 {digest.hexdigest()}")
